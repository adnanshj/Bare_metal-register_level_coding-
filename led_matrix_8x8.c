void repitations(volatile uint8_t arr[],volatile uint8_t size){
  k=0;prev=0;
    //find cummulative repitations of columns 
for(i=1;i<size;i++){
    j=1;
    while(arr[i]==arr[i-1]){
        i++;
        j++;
    }
    pattern[k]=j+prev;
    prev=pattern[k];
    k++;
}
}

